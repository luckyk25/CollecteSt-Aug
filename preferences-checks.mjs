import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {reminderInstant,reminderDue} from './lib/reminder-time.mjs';
import {lookupLocation,resolveSelection} from './lib/addresses.mjs';
import {renderHtml} from './scripts/render-html.mjs';
import streets from './lib/streets.json' with {type:'json'};
const instant=(date,time)=>new Date(reminderInstant(date,time)).toISOString();
assert.equal(instant('2026-10-25','07:37'),'2026-10-25T11:37:00.000Z');
assert.equal(instant('2026-11-08','19:15'),'2026-11-09T00:15:00.000Z');
assert.equal(instant('2026-10-25','00:00'),'2026-10-25T04:00:00.000Z');
assert.equal(instant('2026-10-25','23:59'),'2026-10-26T03:59:00.000Z');
assert.equal(instant('2026-11-01','01:30'),'2026-11-01T05:30:00.000Z');
assert(!reminderDue('2026-11-01','01:30',new Date('2026-11-01T06:30:00Z')));
assert.equal(instant('2026-03-08','02:30'),'2026-03-08T07:30:00.000Z');
assert(reminderDue('2026-03-08','02:30',new Date('2026-03-08T07:30:00Z')));
assert(!reminderDue('2026-10-25','07:37',new Date('2026-10-25T11:36:59Z')));
assert(reminderDue('2026-10-25','07:37',new Date('2026-10-25T11:41:59Z')));
assert(!reminderDue('2026-10-25','07:37',new Date('2026-10-25T11:42:00Z')));
// Public municipal coordinates are test data, never the user's position.
const street=streets.streets.find(s=>s.id==='5229'),[longitude,latitude]=street.segments[0].paths[0][0];
const location={latitude,longitude,accuracy:5},selected=lookupLocation(location);
assert.equal(selected.streetId,street.id);assert.equal(selected.address,street.name);assert(selected.sector);
assert(!('latitude' in selected)&&!('longitude' in selected));
assert.equal(resolveSelection(selected.address,street.id,selected.sector,location).sector,selected.sector);
assert.throws(()=>resolveSelection('different street',street.id,selected.sector,location));
for(const data of [null,{latitude:0,longitude:0,accuracy:5},{latitude,longitude,accuracy:10000},{latitude:'46',longitude,accuracy:5}])assert.throws(()=>lookupLocation(data));
const html=renderHtml();
assert(html.includes('placeholder="123 rue Exemple"'));assert(!/\{\{[A-Z_]+\}\}/.test(html));
assert(!/<input[^>]*id="address"[^>]*\bvalue=/.test(html));
assert(!html.includes('Vitrier'));assert(html.includes('type="time"'));assert(html.includes('Utiliser ma position'));
assert.equal(readFileSync('app/page-html.ts','utf8'),'export default '+JSON.stringify(html)+';\n');
console.log('Preference checks passed: Québec minute precision, midnight, summer/winter and DST changes, validated location, outside/imprecise location rejection, empty initial address and generic placeholder.');
